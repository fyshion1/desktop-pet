const { contextBridge, ipcRenderer } = require('electron')
contextBridge.exposeInMainWorld('pet', {
  wakeConfig: () => ipcRenderer.invoke('pet:wake-config'),
  wakeOpen: () => ipcRenderer.invoke('pet:wake-open'),
  wakeData: bytes => ipcRenderer.send('pet:wake-data', bytes),
  wakeClose: () => ipcRenderer.send('pet:wake-close'),
  onWake: fn => { const f = (_, data) => fn(data); ipcRenderer.on('pet:wake', f); return () => ipcRenderer.removeListener('pet:wake', f) },
  onSocial: fn => { const f = (_, data) => fn(data); ipcRenderer.on('pet:social', f); return () => ipcRenderer.removeListener('pet:social', f) },
  onSocialError: fn => { const f = (_, data) => fn(data); ipcRenderer.on('pet:social-error', f); return () => ipcRenderer.removeListener('pet:social-error', f) },
  setPresence: value => ipcRenderer.invoke('pet:presence-set', value),
  onPresence: fn => { const f = (_, data) => fn(data); ipcRenderer.on('pet:presence', f); return () => ipcRenderer.removeListener('pet:presence', f) },
  voiceConfig: () => ipcRenderer.invoke('pet:voice-config'),
  voiceOpen: options => ipcRenderer.invoke('pet:voice-open', options),
  voiceData: data => ipcRenderer.send('pet:voice-data', data),
  voiceClose: () => ipcRenderer.send('pet:voice-close'),
  onVoice: fn => { const f = (_, data) => fn(data); ipcRenderer.on('pet:voice', f); return () => ipcRenderer.removeListener('pet:voice', f) },
  bootstrap: () => ipcRenderer.invoke('pet:bootstrap'),
  selectSession: value => ipcRenderer.invoke('pet:session', value),
  resizeBubble: value => ipcRenderer.invoke('pet:resize-bubble', value),
  scale: value => ipcRenderer.invoke('pet:scale', value),
  contextMenu: () => ipcRenderer.send('pet:context-menu'),
  onDock: fn => ipcRenderer.on('pet:docked', (_, edge) => fn(edge)),
  dock: edge => ipcRenderer.invoke('pet:dock', edge),
  bubbleOpen: value => ipcRenderer.send('pet:bubble-open', value),
  speechVisible: value => ipcRenderer.send('pet:speech-visible', value),
  pokeModel: value => ipcRenderer.invoke('pet:poke-model', value),
  actorRatio: value => ipcRenderer.send('pet:actor-ratio', value),
  onPlacement: fn => ipcRenderer.on('pet:placement', (_, value) => fn(value)),
  theme: value => ipcRenderer.invoke('pet:theme', value),
  chooseModel: () => ipcRenderer.invoke('pet:choose-model'),
  model: value => ipcRenderer.invoke('pet:model', value),
  autoHide: value => ipcRenderer.invoke('pet:auto-hide', value),
  autoSpeak: value => ipcRenderer.invoke('pet:auto-speak', value),
  reveal: () => ipcRenderer.send('pet:reveal'),
  engaged: value => ipcRenderer.send('pet:engaged', value),
  onFold: fn => ipcRenderer.on('pet:fold', (_, value) => fn(value)),
  history: () => ipcRenderer.invoke('pet:history'),
  send: payload => ipcRenderer.invoke('pet:send', payload),
  upload: payload => ipcRenderer.invoke('pet:upload', payload),
  cancelSend: () => ipcRenderer.send('pet:cancel-send'),
  toolsState: () => ipcRenderer.invoke('pet:tools-state'),
  setNetwork: enabled => ipcRenderer.invoke('pet:network-toggle', enabled),
  openTools: () => ipcRenderer.send('pet:tools-home'),
  onTool: fn => { const f = (_, data) => fn(data); ipcRenderer.on('pet:tool', f); return () => ipcRenderer.removeListener('pet:tool', f) },
  onReminders: fn => { const f = (_, data) => fn(data); ipcRenderer.on('pet:reminders', f); return () => ipcRenderer.removeListener('pet:reminders', f) },
  tts: text => ipcRenderer.invoke('pet:tts', text),
  stopSpeech: () => ipcRenderer.send('pet:stop-speech'),
  onDelta: fn => { const f = (_, data) => fn(data); ipcRenderer.on('pet:delta', f); return () => ipcRenderer.removeListener('pet:delta', f) },
  onProgress: fn => ipcRenderer.on('pet:progress', (_, data) => fn(data)),
  hit: hit => ipcRenderer.send('pet:hit', !!hit),
  // point 可选：触屏没有全局光标，拖动必须由触点坐标驱动（screenX/screenY）。
  drag: (active, point) => ipcRenderer.send('pet:drag', !!active, point || null),
  dragMove: point => ipcRenderer.send('pet:drag-move', point || null),
  openHome: () => ipcRenderer.send('pet:home'),
  hide: () => ipcRenderer.send('pet:hide'),
  onCursor: fn => { const f = (_, p) => fn(p); ipcRenderer.on('pet:cursor', f); return () => ipcRenderer.removeListener('pet:cursor', f) },
  onOpen: fn => { const f = () => fn(); ipcRenderer.on('pet:open', f); return () => ipcRenderer.removeListener('pet:open', f) },
  onVisibility: fn => { const f = (_, visible) => fn(visible); ipcRenderer.on('pet:visibility', f); return () => ipcRenderer.removeListener('pet:visibility', f) },
  onDisplay: fn => { const f = () => fn(); ipcRenderer.on('pet:display', f); return () => ipcRenderer.removeListener('pet:display', f) },
})
