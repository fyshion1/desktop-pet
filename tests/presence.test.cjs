const { test } = require('node:test')
const assert = require('node:assert/strict')
const { evaluate, transition } = require('../electron/presence.cjs')
const morning = Date.parse('2026-10-21T08:00:00+08:00')
test('sleep protection never grants contact and explicit permit expires across midnight', () => {
  assert.equal(evaluate({}, morning).allowed, false)
  assert.equal(evaluate({}, morning).protectedHours, true)
  const state = transition({}, 'available', 30, morning)
  assert.equal(evaluate(state, morning).allowed, true)
  assert.equal(evaluate(JSON.parse(JSON.stringify(state)), morning + 30 * 60000).mode, 'quiet')
  const late = Date.parse('2026-10-21T23:50:00+08:00')
  const permit = transition({}, 'available', 30, late)
  assert.equal(evaluate(permit, late + 15 * 60000).allowed, true)
  assert.equal(evaluate(permit, late + 31 * 60000).allowed, false)
})
test('rest persists across schedules and waking requires a twenty minute buffer', () => {
  const rest = transition({}, 'rest', 30, morning)
  assert.equal(evaluate(rest, morning + 12 * 3600000).mode, 'rest')
  const awake = transition(rest, 'available', 60, morning)
  assert.equal(evaluate(awake, morning).allowed, false)
  assert.equal(evaluate(awake, morning + 20 * 60000).allowed, true)
  assert.equal(evaluate(transition(awake, 'busy', 30, morning), morning).allowed, false)
  assert.equal(evaluate({ mode: 'available', until: Infinity }, morning).allowed, false)
})

test('warm companionship persists overnight without an expiry, manual quiet still stops it', () => {
  const warm = transition({}, 'warm', 30, morning)
  const restored = JSON.parse(JSON.stringify(warm))
  assert.equal(evaluate(restored, morning + 24 * 3600000).allowed, true)
  assert.equal(evaluate(transition(warm, 'quiet', 30, morning), morning).allowed, false)
})
