const { test } = require('node:test')
const assert = require('node:assert/strict')
test('poke requires two quick releases; a single or long press never triggers', async () => {
  const { PokeGesture } = await import('../src/pokeGesture.js')
  const g = new PokeGesture()
  g.down(10, 10, 0); assert.equal(g.up(10, 10, 50), false)
  g.down(10, 10, 180); assert.equal(g.up(10, 10, 230), true)
  g.down(10, 10, 280); assert.equal(g.up(10, 10, 330), false)
  g.down(10, 10, 500); assert.equal(g.up(10, 10, 900), false)
})
test('a small drag, movement back, cancellation, distant clicks and stale taps cannot become a poke', async () => {
  const { PokeGesture } = await import('../src/pokeGesture.js')
  const g = new PokeGesture()
  g.down(10, 10, 0); g.up(10, 10, 50)
  g.down(10, 10, 100); assert.equal(g.move(14, 10), true); g.move(10, 10)
  assert.equal(g.up(10, 10, 150), false)
  g.down(10, 10, 200); assert.equal(g.up(10, 10, 250), false)
  g.reset(); g.down(10, 10, 300); assert.equal(g.up(10, 10, 350), false)
  g.down(80, 80, 400); assert.equal(g.up(80, 80, 450), false)
  g.down(80, 80, 1000); assert.equal(g.up(80, 80, 1050), false)
})
